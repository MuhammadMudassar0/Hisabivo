export function shiftMonth(month: string, offset: number) {
  const d = new Date(`${month}-01T12:00:00`);
  d.setMonth(d.getMonth() + offset);
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}`;
}
export function monthSummary(entries: Transaction[], month: string) {
  const cash = expenseCashRows(entries);
  const cashRows = cash.filter(e => transactionDate(e).slice(0,7) === month);
  const end = new Date(`${month}-01T12:00:00Z`); end.setUTCMonth(end.getUTCMonth()+1); end.setUTCDate(0); const asOf=end.toISOString().slice(0,10);
  const rows = entries.filter(e => e.payment_tracking ? e.date.slice(0,7) === month || (e.payments || []).some(p => p.date.slice(0,7) === month) : transactionDate(e).slice(0,7) === month).sort((a,b)=>transactionDate(b).localeCompare(transactionDate(a)) || b.created_at.localeCompare(a.created_at));
  const income = cashRows.filter(e=>e.type === "income").reduce((s,e)=>s+e.amount_paisa,0);
  const expense = cashRows.filter(e=>e.type === "expense").reduce((s,e)=>s+e.amount_paisa,0);
  const expectedRows = rows.filter(e=>e.type === "expense" && e.date.slice(0,7) === month && expenseRemaining(e,asOf)>0);
  const expected = expectedRows.reduce((s,e)=>s+expenseRemaining(e,asOf),0);
  const opening = cash.filter(e=>transactionDate(e)<`${month}-01`).reduce((s,e)=>s+(e.type === "income"?e.amount_paisa:-e.amount_paisa),0);
  return {rows,cashRows,income,expense,net:income-expense,opening,closing:opening+income-expense,expected,expectedRows};
}
export function monthEnd(month:string) { const d=new Date(`${month}-01T12:00:00Z`);d.setUTCMonth(d.getUTCMonth()+1);d.setUTCDate(0);return d.toISOString().slice(0,10); }
export function pendingExpenses(entries: Transaction[], month: string) {
  return entries.filter(e=>e.type === "expense" && e.date.slice(0,7)<=month && expenseRemaining(e,monthEnd(month))>0).sort((a,b)=>a.date.localeCompare(b.date)||a.created_at.localeCompare(b.created_at));
}
export function categoryTotals(entries: Transaction[], type: EntryType = "expense") {
  const totals = new Map<string, number>();
  expenseCashRows(entries).filter(e => e.type === type).forEach(e => totals.set(e.category, (totals.get(e.category) || 0) + e.amount_paisa));
  return [...totals.entries()].map(([name, amount]) => ({ name, amount })).sort((a, b) => b.amount - a.amount || a.name.localeCompare(b.name));
}

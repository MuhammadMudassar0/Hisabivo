export function today() {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}
export function validDate(value: string) {
  return /^\d{4}-\d{2}-\d{2}$/.test(value) && value >= "1900-01-01" && value <= "9999-12-31" && !Number.isNaN(Date.parse(value)) && new Date(`${value}T12:00:00Z`).toISOString().slice(0, 10) === value;
}
export function parseAmount(value: string) {
  return parsePkrAmount(value);
}
export function validateEntry(input: EntryInput) {
  if (!["income", "expense"].includes(input.type)) throw new Error("Choose income or expense.");
  if (!Number.isSafeInteger(input.amount_paisa) || input.amount_paisa <= 0 || input.amount_paisa > 99999999999) throw new Error("Enter a valid amount.");
  if (!validDate(input.date)) throw new Error("Choose a valid date from 1900 onward.");
  if (!input.description.trim() || input.description.length > 100) throw new Error("Enter a description of up to 100 characters.");
  if (!input.category.trim() || input.category.length > 60) throw new Error("Choose a category of up to 60 characters.");
  if (!paymentMethods.includes(input.payment_method)) throw new Error("Choose a payment method.");
  if(input.payment_tracking){if(input.type!=="expense"||!Array.isArray(input.payments))throw new Error("A tracked bill needs its payment history.");const ids=new Set<string>();let paid=0;for(const p of input.payments){if(!p.id||ids.has(p.id)||!Number.isSafeInteger(p.amount_paisa)||p.amount_paisa<=0||!validDate(p.date)||!paymentMethods.includes(p.payment_method)||p.notes.length>500)throw new Error("This payment history is invalid.");ids.add(p.id);paid+=p.amount_paisa;}if(paid>input.amount_paisa)throw new Error("The total cannot be less than recorded payments.");}
  if (input.notes.length > 500) throw new Error("Notes must be 500 characters or fewer.");
  if (input.expense_status !== undefined && !["paid", "expected", "partial"].includes(input.expense_status)) throw new Error("Choose a paid or expected expense.");
  if (input.type === "income" && input.expense_status !== undefined && input.expense_status !== "paid") throw new Error("Only expenses can be marked expected.");
  if (input.paid_date != null && (typeof input.paid_date !== "string" || !validDate(input.paid_date))) throw new Error("Choose a valid payment date from 1900 onward.");
  if ((input.type === "income" || input.expense_status === "expected") && input.paid_date != null) throw new Error("Only paid expenses can have a payment date.");
}
export function normalizeEntry<T extends EntryInput>(input: T): Omit<T, "expense_status" | "paid_date"> & { expense_status: "paid" | "expected" | "partial"; paid_date: string | null } {
  if (input.expense_status !== undefined && !["paid", "expected", "partial"].includes(input.expense_status)) throw new Error("Choose a paid or expected expense.");
  if (input.type === "income" && input.expense_status !== undefined && input.expense_status !== "paid") throw new Error("Only expenses can be marked expected.");
  if (input.payment_tracking && input.type === "expense") { const paid = expensePaid(input); return { ...input, expense_status: paid >= input.amount_paisa ? "paid" : paid > 0 ? "partial" : "expected", paid_date: paid >= input.amount_paisa ? [...(input.payments || [])].sort((a,b) => b.date.localeCompare(a.date))[0]?.date || null : null }; }
  if (input.type === "income") return { ...input, expense_status: "paid", paid_date: null };
  const expense_status = input.expense_status || "paid";
  return { ...input, expense_status, paid_date: expense_status === "expected" ? null : input.paid_date || input.date };
}
export function isExpectedExpense(entry: EntryInput) {
  return entry.type === "expense" && entry.expense_status === "expected";
}
export function expensePaid(entry: EntryInput, asOf = "9999-12-31") {
  if (entry.type !== "expense") return 0;
  if (entry.payment_tracking) return (entry.payments || []).filter(p => p.date <= asOf).reduce((sum,p) => sum + p.amount_paisa, 0);
  return !isExpectedExpense(entry) && (entry.paid_date || entry.date) <= asOf ? entry.amount_paisa : 0;
}
export function expenseRemaining(entry: EntryInput, asOf = "9999-12-31") { return Math.max(0, entry.amount_paisa - expensePaid(entry,asOf)); }
export function expenseCashRows(entries: Transaction[]): Transaction[] {
  return entries.flatMap(entry => entry.type === "expense" && entry.payment_tracking ? (entry.payments || []).filter(p=>!p.advance_id).map(p => ({ ...entry, id: `${entry.id}:${p.id}`, amount_paisa:p.amount_paisa, date:p.date, paid_date:p.date, payment_method:p.payment_method, account_id:p.account_id||null, notes:p.notes || entry.notes, created_at:p.created_at, expense_status:"paid" as const, payment_tracking:false, payments:[] })) : isExpectedExpense(entry) ? [] : [entry]);
}
export function isCashEntry(entry: EntryInput) { return !isExpectedExpense(entry) && !entry.payment_tracking; }
export function transactionDate(entry: EntryInput) {
  return entry.type === "expense" && !isExpectedExpense(entry) ? entry.paid_date || entry.date : entry.date;
}
export function money(paisa: number, decimals = false) {
  return `Rs ${new Intl.NumberFormat("en-PK", { minimumFractionDigits: decimals ? 2 : 0, maximumFractionDigits: 2 }).format(paisa / 100)}`;
}
